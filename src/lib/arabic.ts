/**
 * تطبيع النص العربي لأغراض المطابقة (كشف التكرار).
 *
 * منطق سلاسل نصية بحت بلا أي اعتماديات — آمن للاستيراد في الخادم (Node) وفي
 * المتصفح على حدٍّ سواء. لا يُستخدم للعرض، بل لتوليد مفتاح مطابقة موحّد بحيث
 * تُعتبر "الأُنْشُودَة" و"الانشوده" و"الانشودة  " عنواناً واحداً.
 */

// التشكيل (الفتحة/الضمة/الكسرة/الشدة/السكون/التنوين…) والألف الخنجرية.
const DIACRITICS_RE = /[ً-ْٰ]/g;
// التطويل (الكشيدة).
const TATWEEL_RE = /ـ/g;
// الأرقام العربية-الهندية ٠١٢٣٤٥٦٧٨٩.
const ARABIC_DIGITS_RE = /[٠-٩]/g;
// كل ما ليس حرفاً عربياً أو لاتينياً أو رقماً أو مسافة (علامات ترقيم ورموز).
const NON_WORD_RE = /[^ء-يٱa-z0-9\s]/g;

/**
 * يُرجع مفتاح مطابقة موحّد لعنوان النشيد. عناوين تتطابق بعد التطبيع تُعتبر
 * مكرّرة. سلسلة فارغة تعني عنواناً بلا محتوى قابل للمطابقة.
 */
export function normalizeArabicTitle(input: string): string {
  if (!input) return "";
  return input
    .normalize("NFKC")
    .replace(DIACRITICS_RE, "")
    .replace(TATWEEL_RE, "")
    // توحيد صور الألف والهمزة والتاء المربوطة والألف المقصورة.
    .replace(/[آأإٱ]/g, "ا") // آ أ إ ٱ → ا
    .replace(/ة/g, "ه") // ة → ه
    .replace(/ى/g, "ي") // ى → ي
    .replace(/ؤ/g, "و") // ؤ → و
    .replace(/ئ/g, "ي") // ئ → ي
    // الأرقام العربية-الهندية → لاتينية.
    .replace(ARABIC_DIGITS_RE, (d) => String(d.charCodeAt(0) - 0x0660))
    .toLowerCase()
    .replace(NON_WORD_RE, " ")
    .replace(/\s+/g, " ")
    .trim();
}
